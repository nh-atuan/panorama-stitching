#ifndef GROUP16_BRIEF_PATTERN_H
#define GROUP16_BRIEF_PATTERN_H

#include "feature_border.h"
#include <cstdint>

namespace panorama {

// S3 constants, shared by every version. They are not Config fields.
constexpr std::int32_t kBriefTests = 256;
constexpr std::int32_t kBriefPatchRadius = 15;  // 31 x 31 patch
constexpr float kBriefSmoothSigma = 2.0f;
constexpr std::int32_t kBriefSmoothRadius = 4;

static_assert(kBriefPatchRadius <= kFeatureBorder, "S2 border must cover the BRIEF patch");

// Test k compares the smoothed intensity at keypoint + (ax, ay) with keypoint + (bx, by);
// every offset lies in [-kBriefPatchRadius, kBriefPatchRadius].
struct BriefTest {
    std::int8_t ax, ay, bx, by;
};

// Generated by tests/tool_gen_brief_pattern.py; see src/brief_pattern.cpp.
extern const BriefTest kBriefPattern[kBriefTests];

}  // namespace panorama

#endif  // GROUP16_BRIEF_PATTERN_H
